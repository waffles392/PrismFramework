// swift-tools-version: 6.2

import PackageDescription

// MARK: - Prism
//
// a framework for making 2D games in Swift + SDL3 GPU.
//
// the C/C++ targets at the bottom live under 'C/Sources/' but are declared
// here on purpose: SwiftPM forbids a package consumed by URL from depending on
// a local 'path:' package, so the C code has to be a target of this package
// rather than a nested package of its own. keeping it in this file is what
// lets consumers use '.package(url:exact:)'. see C/README.md

// SoLoud mixes on its own thread and miniaudio opens ALSA/PulseAudio at
// runtime, so the Linux link needs both. (macOS and Windows get these from
// their system libraries.) 'unsafeFlags' is not an option here: SwiftPM
// forbids it in a package that is consumed by URL.
#if os(Linux)
let soloudLinkerSettings: [LinkerSetting] = [
    .linkedLibrary("pthread"),
    .linkedLibrary("dl"),
]
#else
let soloudLinkerSettings: [LinkerSetting] = []
#endif

let package: Package = Package(
    name: "prism",

    products: [
        // everything else is an internal target
        // consumers only ever `import Prism`.
        .library(name: "Prism", targets: ["Prism"]),
    ],

    targets: [
        // MARK: CXX (sources in C/Sources - see C/README.md)

        // pkg-config shims over the system libraries.
        .systemLibrary(
            name: "CSDL3",
            path: "C/Sources/CSDL3",
            pkgConfig: "sdl3",
            providers: [
                .brew(["sdl3"]),
                .apt(["libsdl3-dev"]),
            ]
        ),

        // SDL3_image has no Swift-side shim: the only C++ that includes it is
        // CRmlUI's SDL3-GPU backend. it still needs a target of its own so the
        // <SDL3_image/SDL_image.h> include path comes from pkg-config rather
        // than from the header happening to sit on a default search path.
        .systemLibrary(
            name: "CSDL3Image",
            path: "C/Sources/CSDL3Image",
            pkgConfig: "sdl3-image",
            providers: [
                .brew(["sdl3_image"]),
                .apt(["libsdl3-image-dev"]),
            ]
        ),

        .systemLibrary(
            name: "CFreetype",
            path: "C/Sources/CFreetype",
            pkgConfig: "freetype2",
            providers: [
                .brew(["freetype"]),
                .apt(["libfreetype-dev"]),
            ]
        ),

        // Vulkan is only used for its struct and enum definitions: the engine
        // fills in a device feature list and hands it to SDL_GPU, it never
        // calls the Vulkan API directly. the shim drops the prototypes
        .systemLibrary(
            name: "CVulkan",
            path: "C/Sources/CVulkan",
            pkgConfig: "vulkan",
            providers: [
                .brew(["vulkan-loader"]),
                .apt(["libvulkan-dev"]),
            ]
        ),

        // vendored RmlUI core (pinned to 6.3, regenerated by
        // Scripts/vendor_rmlui.py), compiled by SwiftPM.
        .target(
            name: "CRmlUiCore",
            dependencies: ["CFreetype"],
            path: "C/Sources/CRmlUiCore",
            exclude: [
                "LICENSE.txt",
                "README.md",
                "VERSION",
                "Include/RmlUi/Core/Containers/LICENSE.txt",
                "Include/RmlUi/Core/Colour.inl",
                "Include/RmlUi/Core/Element.inl",
                "Include/RmlUi/Core/Matrix4.inl",
                "Include/RmlUi/Core/TypeConverter.inl",
                "Include/RmlUi/Core/Variant.inl",
                "Include/RmlUi/Core/Vector2.inl",
                "Include/RmlUi/Core/Vector3.inl",
                "Include/RmlUi/Core/Vector4.inl",
                "Source/Core/Pool.inl",
            ],
            publicHeadersPath: "Include",
            cxxSettings: [
                .headerSearchPath("Include"),
                .headerSearchPath("Source/Core"),
                .define("RMLUI_STATIC_LIB"),
                .define("RMLUI_FONT_ENGINE_FREETYPE"),
                .define("RMLUI_VERSION", to: "\"6.3\""),
            ]
        ),

        // vendored SoLoud (pinned to a commit, regenerated by
        // Scripts/vendor_soloud.py), compiled by SwiftPM. the engine only ever
        // reaches it through the 'CSoloud' shim below, so its C++ headers are
        // never parsed as C.
        .target(
            name: "CSoloudCore",
            path: "C/Sources/CSoloudCore",
            exclude: ["LICENSE.txt", "README.md", "VERSION"],
            publicHeadersPath: "include",
            cxxSettings: [
                .headerSearchPath("include"),
                .define("WITH_MINIAUDIO"),
                .define("WITH_NULL"),
            ],
            linkerSettings: soloudLinkerSettings
        ),

        // prism's shim over the vendored SoLoud: a module map Swift can import,
        // plus the small C++ bridge for the few pieces SoLoud's own C API
        // leaves out (see C/Sources/CSoloud/include/soloud_bridge.h).
        .target(
            name: "CSoloud",
            dependencies: ["CSoloudCore"],
            path: "C/Sources/CSoloud",
            publicHeadersPath: "include",
            cxxSettings: [
                .headerSearchPath("include"),
                .headerSearchPath("src"),
            ]
        ),

        // prism's C bridge + the RmlUI SDL3-GPU backend that glues RmlUI to
        // the engine (derived from RmlUI - see THIRD_PARTY_NOTICES.md).
        .target(
            name: "CRmlUI",
            dependencies: ["CSDL3", "CSDL3Image", "CFreetype", "CRmlUiCore"],
            path: "C/Sources/CRmlUI",
            sources: [
                "src/RmlUi_Renderer_SDL_GPU.cpp",
                "src/RmlUi_Platform_SDL.cpp",
                "src/rmlui_bridge.cpp",
            ],
            publicHeadersPath: "include",
            cxxSettings: [
                .headerSearchPath("include"),
                .headerSearchPath("src"),
                .define("RMLUI_STATIC_LIB"),
                .define("RMLUI_SDL_VERSION_MAJOR", to: "3"),
            ],
            linkerSettings: [
                .linkedLibrary("SDL3_image"),
            ]
        ),

        // MARK: engine modules

        .target(
            name: "Math",
            path: "Sources/Prism/Math"
        ),

        .target(
            name: "Input",
            dependencies: ["Math", "CSDL3"],
            path: "Sources/Prism/Input"
        ),

        .target(
            name: "Time",
            path: "Sources/Prism/Time"
        ),

        .target(
            name: "Window",
            dependencies: ["CSDL3"],
            path: "Sources/Prism/Window"
        ),

        .target(
            name: "Audio",
            dependencies: ["CSoloud"],
            path: "Sources/Prism/Audio"
        ),

        .target(
            name: "Graphics",
            dependencies: ["Math", "CSDL3", "CVulkan"],
            path: "Sources/Prism/Graphics",
            exclude: ["README.md"],
            resources: [.copy("Shaders")]
        ),

        .target(
            name: "Events",
            dependencies: ["Input", "Math"],
            path: "Sources/Prism/Events"
        ),

        .target(
            name: "Scene",
            dependencies: ["Graphics", "Math"],
            path: "Sources/Prism/Scene"
        ),

        .target(
            name: "UI",
            dependencies: ["CRmlUI", "Graphics", "Math"],
            path: "Sources/Prism/UI"
        ),

        .target(
            name: "Core",
            dependencies: [
                "Graphics", "Scene", "Math", "Input", "Time",
                "Window", "Audio", "UI", "Events",
            ],
            path: "Sources/Prism/Core"
        ),

        // re export
        .target(
            name: "Prism",
            dependencies: [
                "Core", "Scene", "Graphics", "Math", "Input",
                "Time", "Window", "Audio", "UI", "Events",
            ],
            path: "Sources/Prism",
            exclude: [
                "Audio", "Core", "Events", "Graphics",
                "Input", "Math", "Scene", "Time", "UI", "Window",
            ],
            sources: ["Exports.swift"]
        ),

        // MARK: tests
        .testTarget(
            name: "PrismTests",
            dependencies: ["Prism", "Core", "Input", "Time", "Window", "Audio", "Math", "Graphics", "UI", "Events"],
            path: "Tests/PrismTests",
            resources: [.copy("Resources")]
        ),
    ],

    swiftLanguageModes: [.v6],
    cxxLanguageStandard: .cxx17
)
